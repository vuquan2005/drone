#!/usr/bin/env python3
"""Sync paper PDFs to page-based Markdown and embedded images using Poppler."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import quote


PAPERS_DIR = Path(__file__).resolve().parents[1] / "docs/references/papers"
MANIFEST = ".pdf-sync.json"
VERSION = 1


class SyncError(Exception):
    """An extraction failed or existing edits need to be preserved."""


def digest(path):
    hasher = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def run_poppler(*command):
    result = subprocess.run(command, capture_output=True)
    if result.returncode:
        message = result.stderr.decode("utf-8", errors="replace").strip()
        raise SyncError(f"{command[0]}: {message or 'extraction failed'}")
    return result.stdout.decode("utf-8", errors="replace")


def read_manifest(destination):
    path = destination / MANIFEST
    if not path.exists():
        return None
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
        files = state["files"]
        if state["version"] != VERSION or not isinstance(files, dict) or not files:
            raise ValueError("unsupported manifest")
        # All owned outputs live directly in the paper's directory.
        for name, checksum in files.items():
            if (
                not isinstance(name, str)
                or Path(name).name != name
                or name in (".", "..", MANIFEST)
                or not isinstance(checksum, str)
                or not re.fullmatch(r"[0-9a-f]{64}", checksum)
            ):
                raise ValueError("invalid file record")
    except (KeyError, TypeError, ValueError) as error:
        raise SyncError(f"Invalid manifest {path}: {error}") from error
    return state


def check_outputs(destination, state):
    """Refuse to overwrite locally edited files; missing files can be restored."""
    missing = False
    for name, checksum in state["files"].items():
        path = destination / name
        if path.is_symlink():
            raise SyncError(f"Preserving symbolic link: {path}")
        if not path.exists():
            missing = True
        elif not path.is_file() or digest(path) != checksum:
            raise SyncError(f"Preserving edited output: {path}")
    return missing


def markdown(pdf, destination, pages, images, text_mode):
    source_link = quote(os.path.relpath(pdf, destination), safe="/.")
    lines = [
        "<!-- Generated by tools/sync_papers.py; manual edits are protected. -->",
        f"# {pdf.stem}",
        "",
        f"PDF nguồn: [{pdf.name}]({source_link})",
        "",
        f"> Trích xuất tự động bằng pdftotext ({text_mode}) và pdfimages.",
        "> Văn bản được giữ theo trang; chưa khôi phục công thức LaTeX hoặc bảng.",
        "> Hình nhúng được liệt kê theo trang, chưa gán nhãn hay vị trí trong văn bản.",
        "",
    ]
    for number, page in enumerate(pages, 1):
        lines.extend([f"## Trang {number}", ""])
        # A fence preserves columns and prevents PDF text becoming Markdown/HTML.
        fence = "`" * max(3, 1 + max((len(s) for s in re.findall(r"`+", page)), default=0))
        if page.strip():
            lines.extend([f"{fence}text", page.rstrip(), fence, ""])
        else:
            lines.extend(["*Trang không có lớp văn bản; cần OCR nếu là bản scan.*", ""])
        if images.get(number):
            lines.extend(["### Hình nhúng", ""])
            for name in images[number]:
                lines.extend([f"![Trang {number} - {name}]({name})", ""])
    return "\n".join(lines)


def extract(pdf, stage, destination, text_mode):
    command = ["pdftotext", "-enc", "UTF-8"]
    if text_mode == "layout":
        command.append("-layout")
    text = run_poppler(*command, str(pdf), "-")
    pages = text.split("\f")
    if pages and not pages[-1].strip():
        pages.pop()  # pdftotext terminates the last page with a form feed.
    if not any(page.strip() for page in pages):
        raise SyncError(f"No extractable text in {pdf.name}; OCR is required")

    listing = run_poppler("pdfimages", "-list", str(pdf))
    image_pages = {}
    for line in listing.splitlines():
        fields = line.split()
        if len(fields) >= 2 and fields[0].isdigit() and fields[1].isdigit():
            image_pages[int(fields[1])] = int(fields[0])
    run_poppler("pdfimages", "-png", str(pdf), str(stage / "img"))
    images = {}
    for path in sorted(stage.iterdir()):
        match = re.fullmatch(r"img-(\d+)\.[a-z0-9]+", path.name)
        if match:
            page = image_pages.get(int(match[1]))
            if page is None or page > len(pages):
                raise SyncError(f"Cannot map image to a page: {path.name}")
            images.setdefault(page, []).append(path.name)

    (stage / f"{pdf.stem}.md").write_text(
        markdown(pdf, destination, pages, images, text_mode), encoding="utf-8"
    )
    return len(pages), sum(map(len, images.values()))


def sync_paper(pdf, output_dir, *, text_mode="layout", dry_run=False, force=False):
    destination = output_dir / pdf.stem
    if destination.is_symlink():
        raise SyncError(f"Preserving symbolic link: {destination}")
    state = read_manifest(destination)
    if state is None and destination.exists() and any(destination.iterdir()):
        return "KEEP", "existing folder without a sync manifest (manually maintained)"

    missing = check_outputs(destination, state) if state else True
    signature = {
        "source_sha256": digest(pdf),
        "source_path": os.path.relpath(pdf, destination),
        "text_mode": text_mode,
    }
    if state and not missing and not force and all(state.get(k) == v for k, v in signature.items()):
        return "UNCHANGED", "PDF and generated outputs match"
    action = "UPDATE" if state else "CREATE"
    if dry_run:
        return action, "dry run"

    output_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".pdf-sync-", dir=output_dir) as temporary:
        stage = Path(temporary) / "paper"
        stage.mkdir()
        page_count, image_count = extract(pdf, stage, destination, text_mode)
        if digest(pdf) != signature["source_sha256"]:
            raise SyncError(f"PDF changed during extraction; run again: {pdf}")
        files = {path.name: digest(path) for path in stage.iterdir()}
        manifest = {"version": VERSION, "source": pdf.name, **signature, "files": files}
        (stage / MANIFEST).write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )

        # Recheck edits after conversion, before replacing any output.
        if state:
            check_outputs(destination, state)
        elif destination.exists() and any(destination.iterdir()):
            raise SyncError(f"Output folder changed during extraction: {destination}")
        destination.mkdir(parents=True, exist_ok=True)
        previous = state["files"] if state else {}
        for name in files:
            target = destination / name
            if target.is_symlink() or (target.exists() and name not in previous):
                raise SyncError(f"Preserving unmanaged output: {target}")
        for name in files:
            os.replace(stage / name, destination / name)
        for name in previous.keys() - files.keys():
            (destination / name).unlink(missing_ok=True)
        os.replace(stage / MANIFEST, destination / MANIFEST)
    return action, f"{page_count} pages, {image_count} embedded images"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pdfs", nargs="*", type=Path, help="Specific PDFs; default: all in --papers-dir")
    parser.add_argument("--papers-dir", type=Path, default=PAPERS_DIR)
    parser.add_argument("--output-dir", type=Path, help="Default: <papers-dir>/papers_md")
    parser.add_argument("--text-mode", choices=("layout", "reading"), default="layout",
                        help="Preserve columns (layout) or use Poppler's default reading order")
    parser.add_argument("--dry-run", action="store_true", help="Show actions without writing files")
    parser.add_argument("--force", action="store_true", help="Rebuild managed outputs, preserving manual edits")
    args = parser.parse_args(argv)
    papers_dir = args.papers_dir.resolve()
    output_dir = (args.output_dir or papers_dir / "papers_md").resolve()
    pdfs = args.pdfs or sorted(papers_dir.glob("*.[pP][dD][fF]"))
    if not pdfs:
        parser.error(f"No PDFs found in {papers_dir}")
    pdfs = sorted({pdf.resolve() for pdf in pdfs})
    for pdf in pdfs:
        if not pdf.is_file() or pdf.suffix.lower() != ".pdf":
            parser.error(f"Not a PDF file: {pdf}")
    if len({pdf.stem for pdf in pdfs}) != len(pdfs):
        parser.error("PDF filenames must have unique stems in the output directory")
    for executable in ("pdftotext", "pdfimages"):
        if shutil.which(executable) is None:
            parser.error(f"Missing {executable}; install Poppler (Ubuntu/Fedora: poppler-utils)")

    counts = {}
    for pdf in pdfs:
        try:
            action, detail = sync_paper(pdf, output_dir, text_mode=args.text_mode,
                                      dry_run=args.dry_run, force=args.force)
        except (OSError, SyncError) as error:
            action, detail = "ERROR", str(error)
        counts[action] = counts.get(action, 0) + 1
        print(f"{action:9} {pdf.name}: {detail}")
    print("Summary: " + ", ".join(f"{key}={value}" for key, value in sorted(counts.items())))
    return 1 if counts.get("ERROR") else 0


if __name__ == "__main__":
    sys.exit(main())
